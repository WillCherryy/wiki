"""Data for the Build console beyond the summary export: every public task (so each one can be picked), and, for each recorded model run,
the full detail the task inspector shows: tool calls with their arguments and results, the physics checks, and for well tests the
pressure derivative the agent was reading (computed by the engine from the task's own data).

    python -m earthbench.export_console        # writes mockups/suite/console-tasks.js and console-traces.js

Both files are loaded by the console only when needed. Nothing here is simulated: the console's simulated viewers are generated in the
page and marked as such.
"""
from __future__ import annotations
import glob
import gzip
import json
import os
import numpy as np
from .run import PACKS, pack

HERE = os.path.dirname(__file__)
ROOT = os.path.join(HERE, "..")
OUT = os.path.join(ROOT, "mockups", "suite")
RES = os.path.join(HERE, "results")


def _short(v, n):
    s = v if isinstance(v, str) else json.dumps(v, default=str, separators=(",", ":"))
    return s if len(s) <= n else s[: n - 1] + "…"


def tasks():
    rows, briefs = [], []
    for name in PACKS:
        try:
            P = pack(name)
        except ImportError:
            continue
        for su in P.SUITES:
            for t in P.suite(su):
                briefs.append(t.statement)
                rows.append([t.id, name, su, t.kind, t.spec, t.defect, int(bool(t.inject)), t.faults or "",
                             [[f, (v[1] if len(v) > 1 else "") or ""] for f, v in t.answer_fields.items()], len(briefs) - 1])
    try:
        from gisbench import tasks as GT
        for su, ts in (("main", GT.main_suite()), ("hard", GT.hard_suite()), ("injection", GT.injection_suite()), ("stress", GT.stress_suite())):
            for t in ts:
                briefs.append(t.statement)
                rows.append([t.id, "gis", su, "screen", t.spec, t.defect, int(bool(t.inject)), getattr(t, "faults", "") or "",
                             [["suitable_area_ha", "ha"], ["largest_parcel_ha", "ha"], ["feasible", "true or false"], ["clear_sky_yield_gwh", "GWh"]], len(briefs) - 1])
    except Exception as e:                           # gisbench needs its own requirements
        print("gisbench tasks skipped:", e)
    return {"cols": ["id", "pack", "suite", "kind", "spec", "defect", "inject", "faults", "fields", "brief"], "rows": rows, "briefs": briefs}


def traces():
    out = {}
    for f in sorted(glob.glob(os.path.join(RES, "model-*.json"))):
        base = os.path.basename(f)[:-5]
        d = json.load(open(f))
        rp = os.path.join(RES, "records", base + ".jsonl.gz")
        if not os.path.exists(rp):
            continue
        P = pack(d["pack"])
        by_id = None
        run = {}
        for line in gzip.open(rp, "rt"):
            r = json.loads(line)
            tid, rep = r["task"]["id"], (r.get("agent") or {}).get("repeat", 0)
            if rep:
                continue
            a = r["assertions"]
            item = {"c": [[t["tool"], bool(t["ok"]), _short(t.get("args") or {}, 160), _short(t.get("error") or t.get("result"), 240), round(float(t.get("ms") or 0), 1)] for t in r["trace"]],
                    "p": [[k, bool(v["ok"]), v.get("detail", "")] for k, v in (a.get("physics") or {}).items()],
                    "v": sorted({v["kind"] for v in (a.get("violations") or [])}), "stop": (r.get("usage") or {}).get("stop")}
            if d["pack"] == "welltest":
                if by_id is None:
                    by_id = {t.id: t for su in P.SUITES for t in P.suite(su)}
                t = by_id.get(tid)
                if t is not None:
                    th, der = P._deriv_si(t)
                    ok = np.isfinite(der) & (der > 0)
                    k = P.key(t)
                    ans = a.get("answer") or {}
                    item["wt"] = {"t": [round(float(x), 5) for x in np.asarray(th)[ok]], "d": [round(float(x), 1) for x in np.asarray(der)[ok]],
                                  "win": [ans.get("dt_from_h"), ans.get("dt_to_h")], "rad": [k["radial_from_h"], k["radial_to_h"]]}
            run[tid] = item
        out[base] = run
    return out


def main():
    T = tasks()
    p = os.path.join(OUT, "console-tasks.js")
    open(p, "w").write("// Generated by python -m earthbench.export_console: every public task. Do not edit.\nwindow.SB_TASKS = " + json.dumps(T, separators=(",", ":")) + ";\n")
    print(f"wrote {os.path.relpath(p, ROOT)}: {len(T['rows'])} tasks, {os.path.getsize(p) / 1024:.0f} KB")
    R = traces()
    p = os.path.join(OUT, "console-traces.js")
    open(p, "w").write("// Generated by python -m earthbench.export_console: recorded tool calls and checks per task. Do not edit.\nwindow.SB_TRACES = " + json.dumps(R, separators=(",", ":"), default=str) + ";\n")
    print(f"wrote {os.path.relpath(p, ROOT)}: {sum(len(v) for v in R.values())} task runs, {os.path.getsize(p) / 1024:.0f} KB")


if __name__ == "__main__":
    main()
