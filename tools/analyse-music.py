#!/usr/bin/env python3
"""Beat-tracks a music file for the hops advert and writes tools/video/hops-beats.js: the beat times (shifted so the video starts at 0),
the beat on which the first hop starts and the beat on which the logo is revealed. The reveal is put on the biggest 'drop' (jump in
loudness) in the last part of the piece, so the music keeps playing under the end card. Dynamic-programming beat tracker (Ellis 2007) on
a spectral-flux onset curve; numpy only (plus ffmpeg to decode).   usage: python3 tools/analyse-music.py path/to/track.mp3 [--wm SECONDS]"""
import sys, os, json, wave, subprocess, tempfile
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); src = sys.argv[1]
wm_hint = float(sys.argv[sys.argv.index('--wm') + 1]) if '--wm' in sys.argv else None
tmp = tempfile.mktemp(suffix='.wav'); subprocess.run(['ffmpeg', '-y', '-v', 'error', '-i', src, '-ac', '1', '-ar', '22050', tmp], check=True)
w = wave.open(tmp); sr = w.getframerate(); x = np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float32) / 32768; os.remove(tmp)
hop, win = 256, 1024; n = (len(x) - win) // hop; fps = sr / hop
fr = np.lib.stride_tricks.as_strided(x, (n, win), (x.strides[0] * hop, x.strides[0])).copy(); spec = np.abs(np.fft.rfft(fr * np.hanning(win), axis=1))
flux = np.maximum(0, np.diff(np.log1p(spec * 20), axis=0)).sum(1); flux = (flux - flux.mean()) / flux.std()
ac = np.correlate(flux, flux, 'full')[len(flux) - 1:]; lo, hi = int(fps * 60 / 220), int(fps * 60 / 100); bpm0 = 60 * fps / (lo + int(np.argmax(ac[lo:hi])))
def track(flux, bpm, tight=100):
    per = 60 * fps / bpm; n = len(flux); cum = np.zeros(n); back = np.full(n, -1)
    for i in range(n):
        a, b = max(0, int(i - 2 * per)), int(i - per / 2)
        if b <= a: cum[i] = flux[i]; continue
        js = np.arange(a, b); v = cum[js] - tight * np.log((i - js) / per) ** 2; k = int(np.argmax(v)); cum[i] = flux[i] + v[k]; back[i] = js[k]
    i = int(np.argmax(cum[-int(per * 2):])) + n - int(per * 2); out = []
    while i >= 0: out.append(i); i = back[i]
    return np.array(out[::-1]) / fps
beats = track(flux, bpm0)
# loudness per beat, to find the drop near the end
env = np.array([np.sqrt(np.mean(x[int(t * sr):int((t + .4) * sr)] ** 2)) for t in beats])
if wm_hint is None:
    cand = [i for i, t in enumerate(beats) if len(x) / sr - 14 < t < len(x) / sr - 5]
    rise = {i: env[i:i + 4].mean() - env[max(0, i - 6):i].mean() for i in cand}; iwm = max(rise, key=rise.get)
else: iwm = int(np.argmin(abs(beats - wm_hint)))
i_d7 = iwm - 16; i_d0 = i_d7 - 7 * 12; i_start = i_d0 - 4; i_end = iwm + 18
b = beats[i_start:i_end + 2] - beats[i_start]
data = {'b': [round(float(v), 4) for v in b], 'd0': 4, 'wm': 4 + 7 * 12 + 16, 'end': round(float(b[-2]) + .8, 3), 'ta0': round(float(beats[i_start]), 4), 'bpm': round(60 / float(np.median(np.diff(beats))), 1)}
open(os.path.join(HERE, 'video', 'hops-beats.js'), 'w').write('// Generated by tools/analyse-music.py: beat times of the soundtrack, in video time.\nwindow.HB = ' + json.dumps(data) + ';\n'); json.dump(data, open(os.path.join(HERE, 'video', 'hops-beats.json'), 'w'))
print('bpm %.1f | reveal at %.2fs of the track (beat %d), video starts at %.2fs, %.1fs long' % (data['bpm'], beats[iwm], iwm, data['ta0'], data['end']))
